CREATE FUNCTION fourmy_variety_color(p_cultivation text) RETURNS text
LANGUAGE sql STABLE AS $$
  WITH RECURSIVE l AS (
    SELECT p_cultivation AS name, 0 AS depth WHERE p_cultivation IS NOT NULL
    UNION ALL
    SELECT t.parent, l.depth + 1 FROM taxonomy t JOIN l ON t.reference_name = l.name
    WHERE t.parent IS NOT NULL AND l.depth < 30)
  SELECT c.color FROM l JOIN variety_colors c ON c.variety = l.name ORDER BY l.depth LIMIT 1
$$;
GRANT EXECUTE ON FUNCTION fourmy_variety_color(text) TO fourmy_app;
